export const passageOf = (i: ActionItem) =>
    i.foreshadow === undefined
        ? `[상황] ${i.situation}\n[결정타] ${i.elementCue}`
        : `[상황] ${i.situation}\n[복선] ${i.foreshadowCue}\n[결정타] ${i.elementCue}`

/**
 * 지문 표기. 답안에 나올 이유가 없는 문자열이라 밴드가 아니라 검사다 —
 * 길이로 에둘러 잡는 게 아니라 베낀 자국을 직접 잡는다.
 * 9단계가 조망 표지를 forbidWords 에 넣은 것과 같은 자리다.
 *
 * 실측: 좋은 답안 144건 오탐 0 · 기존 뚫기 미검출 3/12 그대로(덤으로 잡는 것 없음)
 *       LEAK_PROBE 13건 누출 0 · 표본 전체 출현 0
 *
 * 셋을 다 넣는다. [상황] 만 막으면 나머지 둘로 시작하는 변형이 남는다.
 */
export const PASSAGE_TAGS = ['[상황]', '[복선]', '[결정타]']

export const actionCfgOf = (i: ActionItem) => ({
    ...AT_CFG,
    requireAny: [i.element],
    requireInLastLine: [i.element],
    forbidWords: PASSAGE_TAGS,
})

