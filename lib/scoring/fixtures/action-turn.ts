export const passageOf = (i: ActionItem) =>
    i.foreshadow === undefined
        ? `[상황] ${i.situation}\n[결정타] ${i.elementCue}`
        : `[상황] ${i.situation}\n[복선] ${i.foreshadowCue}\n[결정타] ${i.elementCue}`

export const actionCfgOf = (i: ActionItem) => ({
    ...AT_CFG,
    requireAny: [i.element],
    requireInLastLine: [i.element],
})

