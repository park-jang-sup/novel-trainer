/**
 * 10단계 action_turn(전투 서사화) — 지문 8건.
 *
 * 근거는 설계서 ch03_scene.json 드릴 3-06(출처 2부 23-1·23-2) 아홉 항목이다.
 * 세션 10 §7-1 이 단계 이름을 '턴제 액션'에서 '전투 서사화'로 바꾼 자리다 —
 * 2부 23-1 이 "전투씬 잘 쓰는 법은 없다 · 동작을 나열하면 중계가 된다"고 한다.
 *
 * 난이도는 검사가 아니라 재료로 가른다. 9단계 povCfgOf 가 difficulty 를 안
 * 쓰는 것과 같다 — 8문항 단계 넷이 예외 없이 그렇다. foreshadow 유무가
 * 9단계 groups 자리이고, validateActionItem 이 그 대응만 강제한다.
 */

export interface ActionItem {
    sourceKey: string
    difficulty: 1 | 2
    /** [상황] 줄 */
    situation: string
    /** [복선] 줄. foreshadow 를 반드시 포함한다. 난이도 2에만 */
    foreshadowCue?: string
    /**
     * 좋은 답안이 실제로 쓰는 낱말. 통짜 매칭이라 짧아야 한다.
     * element/elementCue 를 가른 것과 같은 구조다 — 이 구별이 없어서
     * at-pit-prop 이 '좋은 답안 12건에 복선이 없다'로 죽었다.
     * 있으면 난이도 2, 없으면 1. 채점 설정에는 안 들어간다.
     */
    foreshadow?: string
    /** [결정타] 줄. element 를 반드시 포함한다 */
    elementCue: string
    /**
     * 결정타 요소. requireAny 와 requireInLastLine 에 그대로 들어간다.
     * ★ 한두 어절로 짧게. 줄바꿈에 걸치면 두 검사 다 못 찾는다.
     *   부분 문자열 누출은 덜 걱정해도 된다 — 마지막 줄 요건이 뒤에 있어
     *   요소를 아무 데나 박아서는 못 지나간다.
     */
    element: string
    /** 왜 이것이 결정타가 될 수 있는지 한 줄. 8단계 chain · 9단계 why 자리 */
    why: string
    /** 좋은 답안 18건. 마지막 줄을 짧게 끊은 것이 섞여 있어야 한다 */
    goods: string[]
    /** 뚫기 11건. BYPASS_KINDS 에서 골라 쓴다 */
    bypasses: { key: string; text: string; known?: true }[]
}

