export function validateActionItem(item: ActionItem): string[] {
    const fails: string[] = []
    const p = passageOf(item)
    const shape =
        item.foreshadow === undefined
            ? /^\[상황\] .+\n\[결정타\] .+$/
            : /^\[상황\] .+\n\[복선\] .+\n\[결정타\] .+$/
    // ★ 이 검사는 아직 안 문다. passageOf 가 만든 것을 passageOf 의 조건으로 잰다 —
    //   자기가 만든 것을 자기가 검사한다. verify.ts 의 [꼴 검사는 아직 안 문다]
    //   블록이 그 사실을 감시로 박아 뒀다. 지우지 마라. 덤프 대조가 붙으면 일한다.
    if (!shape.test(p)) fails.push('지문 꼴이 어긋난다')

    // 10단계 지문에는 대사가 없다. passage-rules 의 종결어미 규칙 둘은
    // dialogueLines 가 빈 배열이라 조용히 통과한다 — 그 '조용히'를 막는다.
    const quotes = p.match(/["']/g)?.length ?? 0
    if (quotes > 0) fails.push(`지문에 따옴표가 있다 (${quotes}개)`)

    // 9단계 (groups === 1) !== (difficulty === 1) 과 같은 자리다.
    if ((item.foreshadow === undefined) !== (item.difficulty === 1)) {
        fails.push('복선 유무와 난이도가 안 맞는다')
    }
    // ★ 대칭으로, 조건 없이 잰다. 한쪽만 재면 다른 쪽이 조용히 통과한다.
    if (!item.elementCue.includes(item.element)) fails.push('elementCue 에 element 가 없다')
    if ((item.foreshadowCue === undefined) !== (item.foreshadow === undefined)) {
        fails.push('foreshadowCue 와 foreshadow 중 하나만 있다')
    }
    if (item.foreshadowCue !== undefined && !item.foreshadowCue.includes(item.foreshadow!)) {
        fails.push('foreshadowCue 에 foreshadow 가 없다')
    }
    if (item.foreshadow !== undefined) {
        const n = item.goods.filter((g) => g.includes(item.foreshadow!)).length
        if (n < item.goods.length) fails.push(`좋은 답안 ${item.goods.length - n}건에 복선이 없다`)
    }
    if (item.goods.length !== 18) fails.push(`좋은 답안이 18건이 아니다 (${item.goods.length})`)
    if (item.why.length < 20) fails.push('why 가 너무 짧다')

    // 갈래 목록 고정. 이름이 두 번 갈렸고 두 번 다 사람 눈이 잡았다.
    const kinds = new Set<string>(BYPASS_KINDS)
    for (const b of item.bypasses) if (!kinds.has(b.key)) fails.push(`목록에 없는 뚫기 갈래 (${b.key})`)
    // ★ 빠뜨림도 잡는다. 이게 없으면 갈래 하나가 빠져도 3/11 이 3/10 이 될 뿐이라
    //   미검출 수가 같으면 안 보인다.
    const have = new Set(item.bypasses.map((b) => b.key))
    for (const k of BYPASS_KINDS) if (!have.has(k)) fails.push(`빠진 뚫기 갈래 (${k})`)
    return fails
}
